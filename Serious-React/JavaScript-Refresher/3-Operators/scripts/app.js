// Operators

// Addition
console.log(10 + 5);
console.log("My Name is " + "Kunal");

// Subtract
console.log(10 - 5);

// Multiplication
console.log(10 * 5);

// Divison
console.log(10 / 5);

// Comparison Operators
// ===
// returns Boolean
console.log(10 === 5); // false
console.log(10 === 10); // true
console.log(10 == "10"); // true (checks only value and not data type)

// <, <=, >, >=
console.log(10 < 5);
console.log(10 <= 10);
console.log(10 > 5);
console.log(10 >= 10);

// if statement
if (10 === 10) {
  console.log("Works");
}
